<#
.SYNOPSIS
    Downloads Microsoft's lists of processors supported by Windows 11 and writes the data file that SystemInfo
    embeds (SystemInfo\Data\windows11-supported-processors.txt).

.DESCRIPTION
    Run it when Microsoft updates the lists (they change with each Windows release), then rebuild SystemInfo.
    Sources:
      https://learn.microsoft.com/windows-hardware/design/minimum/supported/windows-11-supported-intel-processors
      https://learn.microsoft.com/windows-hardware/design/minimum/supported/windows-11-supported-amd-processors

    The Intel page lists series and generations ("10th Generation Core i7 Processors"); the AMD page lists
    individual models. Output lines are tab-separated:  vendor, product / brand, series / model.

.EXAMPLE
    .\update-supported-processors.ps1
#>
param(
    [string]$OutFile = (Join-Path $PSScriptRoot '..\SystemInfo\Data\windows11-supported-processors.txt')
)

$ErrorActionPreference = 'Stop'

$pages = @(
    @{ Vendor = 'intel'; Url = 'https://learn.microsoft.com/en-us/windows-hardware/design/minimum/supported/windows-11-supported-intel-processors' },
    @{ Vendor = 'amd';   Url = 'https://learn.microsoft.com/en-us/windows-hardware/design/minimum/supported/windows-11-supported-amd-processors' }
)

function ConvertTo-PlainText([string]$text) {
    $text = [regex]::Replace($text, '<[^>]+>', '')                     # tags
    $text = [System.Net.WebUtility]::HtmlDecode($text)
    $text = $text.Replace([string][char]0x2122, '').Replace([string][char]0x00AE, '').Replace([string][char]0x00A9, '')   # trademark, registered, copyright signs
    $text = $text.Replace([string][char]0x00A0, ' ')                                                                          # non-breaking space
    ([regex]::Replace($text, '\s+', ' ')).Trim()
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# Windows 11 supported processors, from Microsoft Learn. Generated by docs\update-supported-processors.ps1; do not edit by hand.')
$lines.Add("# Retrieved $(Get-Date -Format 'yyyy-MM-dd'). Format: vendor<TAB>product or brand<TAB>series or model")

foreach ($page in $pages) {
    $html = (Invoke-WebRequest -Uri $page.Url -UseBasicParsing).Content
    $pageDate = [regex]::Match($html, 'name="ms\.date"\s+content="([^"]+)"').Groups[1].Value
    $lines.Add("# $($page.Vendor): page date $pageDate, $($page.Url)")

    $count = 0
    foreach ($row in [regex]::Matches($html, '<tr[^>]*>(.*?)</tr>', 'Singleline')) {
        $cells = @([regex]::Matches($row.Groups[1].Value, '<td[^>]*>(.*?)</td>', 'Singleline') | ForEach-Object { ConvertTo-PlainText $_.Groups[1].Value })
        if ($cells.Count -lt 3 -or $cells[2].Length -eq 0) { continue }
        $lines.Add(('{0}{1}{2}{1}{3}' -f $page.Vendor, "`t", $cells[1], $cells[2]))
        $count++
    }
    if ($count -eq 0) { throw "No rows found in $($page.Url): the page layout may have changed." }
    Write-Host ("{0}: {1} rows" -f $page.Vendor, $count)
}

New-Item -ItemType Directory -Force -Path (Split-Path $OutFile) | Out-Null
# CRLF line endings, as every file of the repository
[System.IO.File]::WriteAllText($OutFile, (($lines -join "`r`n") + "`r`n"), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Written $OutFile"
